PMAX = 24          # must match PMAX in zpolice.asm
GRID = 64          # must match GRID in zpolice.asm

lines = ["; ---- generated by gentables.py - do not edit ----", ""]


def emit_bytes(label, values, per_line=16):
    lines.append(f"{label}:")
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("        db " + ",".join(f"${v & 0xFF:02X}" for v in chunk))
    lines.append("")


def emit_words(label, values, per_line=8):
    lines.append(f"{label}:")
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("        dw " + ",".join(f"${v & 0xFFFF:04X}" for v in chunk))
    lines.append("")


# Sine, S7.8, split into low/high byte pages so a lookup is H=page, L=angle.
sin = [round(256 * math.sin(2 * math.pi * a / 256)) for a in range(256)]
lines.append("        ALIGN 256")
emit_bytes("sin_lo", [s & 0xFF for s in sin])
emit_bytes("sin_hi", [(s >> 8) & 0xFF for s in sin])

# Reciprocal for perspective divide: Z is normalised to Zn in [256,511],
# R = 2^24 / Zn, so  128*X/Z == (Xn * R) >> 17.
rt = [min(65535, round((1 << 24) / (256 + i))) for i in range(256)]
emit_bytes("rtab_lo", [r & 0xFF for r in rt])
emit_bytes("rtab_hi", [r >> 8 for r in rt])

# floor(log2(n)) for normalising Z with the barrel shifter (page aligned).
emit_bytes("lgtab", [0] + [n.bit_length() - 1 for n in range(1, 256)])

# Horizon screen row for each pitch: 64 + 128*tan(pitch), clamped to 0..128
# (the 3D viewport is the top 256x128 of the screen).
hz = []
for p in range(-PMAX, PMAX + 1):
    y = 64 + 128 * math.tan(2 * math.pi * p / 256)
    hz.append(max(0, min(128, round(y))))
emit_bytes("hztab", hz)

# Box faces. Vertex index = x + 2*z + 4*top; face bits as in zpolice.asm
# (bit0 -X, bit1 +X, bit2 -Z, bit3 +Z, bit4 top).
FACES = {0: {0, 2, 6, 4}, 1: {1, 3, 7, 5}, 2: {0, 1, 5, 4}, 3: {2, 3, 7, 6},
         4: {4, 5, 7, 6}}
# corners used by the visible faces (bit n = vertex n)
used = []
for vis in range(32):
    m = 0
    if not ((vis & 3) == 3 or (vis & 12) == 12):
        for f in range(5):
            if vis >> f & 1:
                for v in FACES[f]:
                    m |= 1 << v
    used.append(m)
emit_bytes("used_tab", used)

# Building height per level (level 0 = no building).
# Heights scale linearly to BLD_MAX_H = 7.0 height units (1.0 = 128 world
# units = 10 m) at level 15.
BLD_MAX_H = 7 * 128                    # must match zpolice.asm (height unit = 128)
# Entry 16 (map code PAD_CODE) is the base's landing pad, 0.5 height units high;
# entry 17 (TERRACE_CODE) the terrace round it, 0.25 height units high.
PAD_CODE, PAD_H = 16, 64               # 0.5 height units (5 m)
TERRACE_CODE, TERRACE_H = 17, 32       # 0.25 height units
# Entry 18 (VOID_CODE): out of bounds, outside the city's perimeter wall, so a
# city can be another shape inside the GRID x GRID map.  Never drawn, black
# on the HUD map, nothing placed there; as tall as the wall (BLD_MAX_H), so
# anything that tests heights (collisions, sight, rounds) finds it solid.
VOID_CODE, VOID_H = 18, BLD_MAX_H
emit_words("htab", [round(lvl * BLD_MAX_H / 15) for lvl in range(16)] + [PAD_H, TERRACE_H, VOID_H])
lines.append(f"        ASSERT BLD_MAX_H == {BLD_MAX_H}   ; gentables.py and zpolice.asm agree")
lines.append(f"PAD_CODE        equ {PAD_CODE}      ; map code of the base landing pad")
lines.append(f"TERRACE_CODE    equ {TERRACE_CODE}      ; the terrace round it (0.25 height units)")
lines.append(f"PAD_H           equ {PAD_H}     ; its height (0.5 height units)")
lines.append(f"VOID_CODE       equ {VOID_CODE}      ; out of bounds (outside the perimeter): never drawn")
lines.append("")

