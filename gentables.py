# Zombie sprites (placeholder stick men) -> tables_zombie.inc
# 8 scales, width k+1 (1..8) by height 4..16; facings forward and left, 4
# walk frames each.  Rear and right are drawn mirrored by the game.  One byte
# per row, bit 7 = leftmost pixel.
ZLEVELS = [(k + 1, round(4 + 12 * k / 7)) for k in range(8)]

# Full size (8x16) frames, '#' = pixel.  Smaller levels are box-filtered
# with OR so one-pixel limbs survive the shrink.
Z_TOP_F = ["..###...", "..###...", "..###...", "...#....", ".#####..",
           "#.###.#.", "#.###.#.", "..###...", "..###...", "..#.#..."]
Z_TOP_L = ["...##...", "..###...", "...##...", "...#....", "#####...",
           "...##...", "...##...", "...##...", "...##...", "...##..."]
Z_LEGS = {   # 6 rows each: [facing][frame]
    0: [["..#.#...", "..#.#...", "..#.#...", "..#.#...", "..#.#...", ".##.##.."],
        ["..#.#...", "..#.#...", "..#.#...", ".##.#...", "....#...", "....##.."],
        ["..#.#...", "..#.#...", "..#.#...", "..#.#...", "..#.#...", ".##.##.."],
        ["..#.#...", "..#.#...", "..#.#...", "..#.##..", "..#.....", ".##....."]],
    1: [["..#..#..", "..#..#..", ".#....#.", ".#....#.", "#.....#.", "##....##"],
        ["...#.#..", "...#.#..", "..#..#..", "..#.#...", ".#..#...", "##..##.."],
        ["...##...", "...##...", "...##...", "...##...", "...##...", "..###..."],
        ["...#.#..", "...#.#..", "...#..#.", "...#..#.", "...#..#.", "..##..##"]],
}

def zraster(w, h, facing, frame):
    src = (Z_TOP_F if facing == 0 else Z_TOP_L) + Z_LEGS[facing][frame]
    rows = []
    for y in range(h):
        sy0, sy1 = y * 16 // h, max(y * 16 // h + 1, (y + 1) * 16 // h)
        r = 0
        for x in range(w):
            sx0, sx1 = x * 8 // w, max(x * 8 // w + 1, (x + 1) * 8 // w)
            if any(src[sy][sx] == '#' for sy in range(sy0, sy1) for sx in range(sx0, sx1)):
                r |= 1 << (7 - x)
        rows.append(r)
    return rows

zl = ["; ---- generated by gentables.py - do not edit ----", ""]
zl.append("spr_w:      db " + ",".join(str(w) for w, _ in ZLEVELS))
zl.append("spr_h:      db " + ",".join(str(h) for _, h in ZLEVELS))
lvl_of_h = []
for hp in range(17):
    k = max([i for i, (_, h) in enumerate(ZLEVELS) if h <= hp] or [0])
    lvl_of_h.append(k)
zl.append("; scale level for a projected height of 0..16 pixels")
zl.append("lvl_of_h:   db " + ",".join(str(k) for k in lvl_of_h))
zl.append("; sprite pointers: index (facing*4 + frame)*8 + level")
zl.append("spr_ptr:")
for f in range(2):
    for fr in range(4):
        zl.append("        dw " + ",".join(f"spr_{f}_{fr}_{k}" for k in range(8)))
for f in range(2):
    for fr in range(4):
        for k, (w, h) in enumerate(ZLEVELS):
            rows = zraster(w, h, f, fr)
            zl.append(f"spr_{f}_{fr}_{k}: db " + ",".join(f"${r:02X}" for r in rows))
zl.append("        ALIGN 256")
zl.append("bitrev:")
for i in range(0, 256, 16):
    zl.append("        db " + ",".join(f"${int(f'{v:08b}'[::-1], 2):02X}" for v in range(i, i + 16)))
with open("tables_zombie.inc", "w") as f:
    f.write("\n".join(zl) + "\n")
print("wrote tables_zombie.inc")


