# Same 8 scales and row format as the zombies (spr_w / spr_h / lvl_of_h).
def human_frame(hand_col):
    g = [list("........") for _ in range(16)]
    def put(r, c):
        if 0 <= r < 16 and 0 <= c < 8:
            g[r][c] = "#"
    for r in range(0, 3):
        for c in range(3, 6):
            put(r, c)                       # head
    put(3, 4)                               # neck
    for c in range(3, 6):
        put(4, c)                           # shoulders
    for r in range(5, 10):
        put(r, 4)                           # body
    for r in range(5, 9):
        put(r, 6)                           # left arm (viewer's right), down
    put(4, 6)
    r0, c0, r1, c1 = 4, 2, 0, hand_col      # right arm: shoulder -> hand
    n = max(abs(r1 - r0), abs(c1 - c0))
    for k in range(n + 1):
        put(round(r0 + (r1 - r0) * k / n), round(c0 + (c1 - c0) * k / n))
    for r in range(10, 15):
        put(r, 3); put(r, 5)                # legs
    put(15, 2); put(15, 3); put(15, 5); put(15, 6)   # feet
    return ["".join(row) for row in g]

def shrink(src, w, h):
    rows = []
    for y in range(h):
        sy0, sy1 = y * 16 // h, max(y * 16 // h + 1, (y + 1) * 16 // h)
        r = 0
        for x in range(w):
            sx0, sx1 = x * 8 // w, max(x * 8 // w + 1, (x + 1) * 8 // w)
            if any(src[sy][sx] == '#' for sy in range(sy0, sy1) for sx in range(sx0, sx1)):
                r |= 1 << (7 - x)
        rows.append(r)
    return rows

