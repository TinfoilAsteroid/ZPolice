"""Generate lookup tables and the city map for Z-Police (writes tables.inc).

All trig is S7.8 fixed point (1.0 == 256). Angles are 8-bit (256 == 360 deg).
"""
import math
import random

PMAX = 24          # must match PMAX in zpolice.asm
GRID = 32
OUT = "tables.inc"

lines = ["; ---- generated by gentables.py - do not edit ----", ""]


def emit_bytes(label, values, per_line=16):
    lines.append(f"{label}:")
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("        db " + ",".join(f"${v & 0xFF:02X}" for v in chunk))
    lines.append("")


def emit_words(label, values, per_line=8):
    lines.append(f"{label}:")
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("        dw " + ",".join(f"${v & 0xFFFF:04X}" for v in chunk))
    lines.append("")


# Sine, S7.8, split into low/high byte pages so a lookup is H=page, L=angle.
sin = [round(256 * math.sin(2 * math.pi * a / 256)) for a in range(256)]
lines.append("        ALIGN 256")
emit_bytes("sin_lo", [s & 0xFF for s in sin])
emit_bytes("sin_hi", [(s >> 8) & 0xFF for s in sin])

# Reciprocal for perspective divide: Z is normalised to Zn in [256,511],
# R = 2^24 / Zn, so  128*X/Z == (Xn * R) >> 17.
rt = [min(65535, round((1 << 24) / (256 + i))) for i in range(256)]
emit_bytes("rtab_lo", [r & 0xFF for r in rt])
emit_bytes("rtab_hi", [r >> 8 for r in rt])

# floor(log2(n)) for normalising Z with the barrel shifter (page aligned).
emit_bytes("lgtab", [0] + [n.bit_length() - 1 for n in range(1, 256)])

# Horizon screen row for each pitch: 96 + 128*tan(pitch), clamped to 0..192.
hz = []
for p in range(-PMAX, PMAX + 1):
    y = 96 + 128 * math.tan(2 * math.pi * p / 256)
    hz.append(max(0, min(192, round(y))))
emit_bytes("hztab", hz)

# Box silhouettes. Vertex index = x + 2*z + 4*top. For every combination of
# visible faces (bit0 -X, bit1 +X, bit2 -Z, bit3 +Z, bit4 top) list the
# silhouette as a vertex cycle (edges with exactly one visible neighbour
# face; the bottom is never visible) and the interior edges (two visible
# neighbours). Offsets are index*16 to match the vtx[] layout.
FACES = {  # bit -> vertex set
    0: {0, 2, 6, 4}, 1: {1, 3, 7, 5}, 2: {0, 1, 5, 4}, 3: {2, 3, 7, 6},
    4: {4, 5, 7, 6}, 5: {0, 1, 3, 2},  # 5 = bottom
}
EDGES = [(a, b) for a in range(8) for b in range(a + 1, 8)
         if bin(a ^ b).count("1") == 1]
sil_tab, inner_tab = [], []
for vis in range(32):
    sil_edges, inner = [], []
    for a, b in EDGES:
        adj = [f for f, vs in FACES.items() if a in vs and b in vs]
        nvis = sum(1 for f in adj if f < 5 and vis >> f & 1)
        if nvis == 1:
            sil_edges.append((a, b))
        elif nvis == 2:
            inner.append((a, b))
    cycle = []
    if sil_edges:
        nbr = {}
        for a, b in sil_edges:
            nbr.setdefault(a, []).append(b)
            nbr.setdefault(b, []).append(a)
        if all(len(v) == 2 for v in nbr.values()) and len(nbr) == len(sil_edges):
            cycle = [sil_edges[0][0]]
            prev = None
            while True:
                cur = cycle[-1]
                nxt = [n for n in nbr[cur] if n != prev][0]
                if nxt == cycle[0]:
                    break
                prev = cur
                cycle.append(nxt)
            if len(cycle) != len(nbr):
                cycle = []
    # opposite faces can't both face the camera: impossible view, draw nothing
    if (vis & 3) == 3 or (vis & 12) == 12 or not cycle:
        cycle, inner = [], []
    assert len(cycle) <= 6 and len(inner) <= 3
    row = [len(cycle)] + [v * 16 for v in cycle]
    sil_tab += row + [0] * (8 - len(row))
    row = [len(inner)] + [v * 16 for e in inner for v in e]
    inner_tab += row + [0] * (8 - len(row))
emit_bytes("sil_tab", sil_tab, per_line=8)
# corners used by the visible faces (bit n = vertex n)
used = []
for vis in range(32):
    m = 0
    if not ((vis & 3) == 3 or (vis & 12) == 12):
        for f in range(5):
            if vis >> f & 1:
                for v in FACES[f]:
                    m |= 1 << v
    used.append(m)
emit_bytes("used_tab", used)
emit_bytes("inner_tab", inner_tab, per_line=8)

# Building height per level (level 0 = no building).
emit_words("htab", [lvl * 40 for lvl in range(16)])

# City map: bits 0-3 height level (0 = empty), bit 4 = tower footprint.
# Every 8th row/column is an open boulevard.
rng = random.Random(1984)
city = []
for j in range(GRID):
    for i in range(GRID):
        if i % 8 == 0 or j % 8 == 0 or rng.random() < 0.10:
            city.append(0)
            continue
        d = math.hypot(i - 16, j - 16)
        lvl = 1 + rng.randint(0, 3) + int(max(0.0, 9 - d * 0.75) * rng.random())
        lvl = min(15, lvl)
        tower = lvl >= 8 or rng.random() < 0.25
        city.append(lvl | (0x10 if tower else 0))
emit_bytes("city_map", city, per_line=32)

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {OUT}")
